uint8_t EcuHardReset (void)
{
    Nvm_Shutdown();
    if(false == HardReset_b)
	{
		HardReset_b = true;
		PblParam_St.DiagSecurityState_u8 = 0;
		
		UpdateNVMblock(PBL_NVM_BLOCK);
	}
    return true;
}

