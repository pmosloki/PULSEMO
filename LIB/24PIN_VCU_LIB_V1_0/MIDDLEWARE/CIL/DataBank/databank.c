uint8_t Get_GPInput_State(GpInputSignal_En_t GPI_Channel_Num)
{
	return DInpSignal_aSt[GPI_Channel_Num].SignalState_u8;	
}

uint16_t Get_ADC_Result(AdcInput_En_t ADC_Channel_Num)
{
	return AdcInpSignal_aSt[ADC_Channel_Num].PresentAdc_u16;
}

